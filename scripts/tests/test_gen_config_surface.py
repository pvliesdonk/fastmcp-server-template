        assert "X_OPT" in region_b and "X_REQ" not in region_b

        target.write_text(once, encoding="utf-8")
        twice = g.render_splice_file(
            tmp_path, "doc.md", file_spec, [v_required, v_optional], ctx
        )
        assert twice == once



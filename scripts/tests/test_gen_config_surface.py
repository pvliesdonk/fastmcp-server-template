class TestCleanHelpForMarkdownTable:
    """Fix round 4: a spliced table cell lands in `docs/`, which every
    downstream lints with Vale at `MinAlertLevel = error`. Core's field
    metadata (already published in v4.5.0, so it cannot be fixed at
    source) carries a spaced em dash and `e.g.` Latin abbreviations that
    trip that lint — but only in this destination; the env-file/wizard
    paths are plain text Vale never lints."""

    def test_em_dash_before_a_conjunction_splits_into_two_sentences(self):
        text = g._clean_help_for_markdown_table(
            "so tokens survive a restart — but rotating that secret "
            "invalidates every issued token."
        )
        assert " — " not in text
        assert "restart. Rotating" in text

    def test_em_dash_without_a_known_conjunction_joins_with_a_semicolon(self):
        text = g._clean_help_for_markdown_table(
            "unset — it then backs every namespace, not just HTTP resumability."
        )
        assert " — " not in text
        assert "unset; it then backs" in text

    def test_eg_clause_becomes_a_parenthetical(self):
        """Deliberately not 'for example,': that phrasing satisfies
        Google.Latin but trips ai-tells.FormalTransitions for this shape of
        sentence — verified against the live Vale ruleset during
        development, not merely assumed."""
        text = g._clean_help_for_markdown_table(
            "Public base URL of the deployed server, e.g. "
            "`https://mcp.example.com`. Required for OIDC."
        )
        assert "e.g." not in text
        assert "(`https://mcp.example.com`)" in text

    def test_eg_clause_terminator_lookahead_does_not_stop_at_a_url_dot(self):
        """A URL's own periods (`mcp.example.com`) must not be mistaken for
        the sentence-ending period that closes the `e.g.` clause."""
        text = g._clean_help_for_markdown_table(
            "OIDC discovery document URL, e.g. "
            "`https://auth.example.com/.well-known/openid-configuration`."
        )
        assert "e.g." not in text
        assert "(`https://auth.example.com/.well-known/openid-configuration`)." in text

    def test_for_example_is_folded_onto_the_eg_rules(self):
        """pvl-core 5.0's own wording (#285): the two shapes it ships, plus the
        sentence-initial one; a non-transitional 'for example' is left alone."""
        text = g._clean_help_for_markdown_table(
            "Public base URL of the deployed server, for example "
            "`https://mcp.example.com`. Required for OIDC."
        )
        assert "for example" not in text

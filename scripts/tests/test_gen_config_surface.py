def _marker_pair(region_id: str) -> str:
    """Stand-in text for one spliced region: an empty, already-marked region.

    Mirrors `_generated_region_markers` exactly (not re-imported, since a
    fixture must not depend on the function under test producing its own
    expected input).
    """
    return (
        f"<!-- GENERATED-ENV-TABLE-{region_id}-START — generated by "
        "scripts/gen_config_surface.py; do not edit -->\n"
        f"<!-- GENERATED-ENV-TABLE-{region_id}-END -->\n"
    )



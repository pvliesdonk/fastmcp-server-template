class TestRenderSpliceFileMultiRegion:
    def test_two_regions_splice_in_one_pass_and_stay_idempotent(self, tmp_path):
        target = tmp_path / "doc.md"
        target.write_text(
            "# Doc\n\n"
            "## Required\n\n"
            "<!-- GENERATED-ENV-TABLE-A-START — generated by "
            "scripts/gen_config_surface.py; do not edit -->\n"
            "<!-- GENERATED-ENV-TABLE-A-END -->\n\n"
            "## Optional\n\n"
            "<!-- GENERATED-ENV-TABLE-B-START — generated by "
            "scripts/gen_config_surface.py; do not edit -->\n"
            "<!-- GENERATED-ENV-TABLE-B-END -->\n",
            encoding="utf-8",
        )
        v_required = g.Var(
            name="X_REQ",
            suffix="REQ",
            provenance="template",
            type_name="str",
            default=None,
            help="Required one.",
            tags=("t",),
            inferred=False,
            wizard={},
        )
        v_optional = g.Var(
            name="X_OPT",
            suffix="OPT",
            provenance="template",
            type_name="str",
            default="v",
            help="Optional one.",
            tags=("t",),
            inferred=False,
            wizard={},
        )
        file_spec = {
            "regions": [
                {"id": "A", "tags": ["t"], "required": True, "columns": ["variable"]},
                {"id": "B", "tags": ["t"], "required": False, "columns": ["variable"]},
            ]
        }
        once = g.render_splice_file(
            tmp_path, "doc.md", file_spec, [v_required, v_optional]
        )
        region_a = once.split("GENERATED-ENV-TABLE-A-START")[1].split(
            "GENERATED-ENV-TABLE-A-END"
        )[0]
        region_b = once.split("GENERATED-ENV-TABLE-B-START")[1].split(
            "GENERATED-ENV-TABLE-B-END"
        )[0]
        assert "X_REQ" in region_a and "X_OPT" not in region_a
        assert "X_OPT" in region_b and "X_REQ" not in region_b

        target.write_text(once, encoding="utf-8")
        twice = g.render_splice_file(
            tmp_path, "doc.md", file_spec, [v_required, v_optional]
        )
        assert twice == once


class TestCleanHelpForMarkdownTable:
    """Fix round 4: a spliced table cell lands in `docs/`, which every
    downstream lints with Vale at `MinAlertLevel = error`. Core's field
    metadata (already published in v4.5.0, so it cannot be fixed at
    source) carries a spaced em dash and `e.g.` Latin abbreviations that
    trip that lint — but only in this destination; the env-file/wizard
    paths are plain text Vale never lints."""

    def test_em_dash_before_a_conjunction_splits_into_two_sentences(self):
        text = g._clean_help_for_markdown_table(
            "so tokens survive a restart — but rotating that secret "
            "invalidates every issued token."
        )
        assert " — " not in text
        assert "restart. Rotating" in text

    def test_em_dash_without_a_known_conjunction_joins_with_a_semicolon(self):
        text = g._clean_help_for_markdown_table(
            "unset — it then backs every namespace, not just HTTP resumability."
        )
        assert " — " not in text
        assert "unset; it then backs" in text

    def test_eg_clause_becomes_a_parenthetical(self):
        """Deliberately not 'for example,': that phrasing satisfies
        Google.Latin but trips ai-tells.FormalTransitions for this shape of
        sentence — verified against the live Vale ruleset during
        development, not merely assumed."""
        text = g._clean_help_for_markdown_table(
            "Public base URL of the deployed server, e.g. "
            "`https://mcp.example.com`. Required for OIDC."
        )
        assert "e.g." not in text
        assert "(`https://mcp.example.com`)" in text

    def test_eg_clause_terminator_lookahead_does_not_stop_at_a_url_dot(self):
        """A URL's own periods (`mcp.example.com`) must not be mistaken for
        the sentence-ending period that closes the `e.g.` clause."""
        text = g._clean_help_for_markdown_table(
            "OIDC discovery document URL, e.g. "
            "`https://auth.example.com/.well-known/openid-configuration`."
        )
        assert "e.g." not in text
        assert "(`https://auth.example.com/.well-known/openid-configuration`)." in text

    def test_ie_becomes_that_is(self):
        text = g._clean_help_for_markdown_table("Uses an alias, i.e. a friendly name.")
        assert "i.e." not in text
        assert "that is, a friendly name." in text

    def test_text_without_any_of_the_patterns_is_unchanged(self):
        text = "Plain help text with no special punctuation."
        assert g._clean_help_for_markdown_table(text) == text


class TestMarkdownVocabularyNormalisation:
    """Vale's spell-check is driven by `.vale/styles/config/vocabularies/
    Base/accept.txt`, which is `_skip_if_exists` — an existing downstream
    keeps its own copy forever, so a term added there reaches only fresh
    renders. The generated table text, by contrast, arrives on every
    `copier update`. Vocabulary therefore has to be normalised on the
    generator side, the only lever that propagates."""

    def test_jwts_does_not_reach_a_spliced_docs_table(self, fake_project):
        """End to end through `write_artifacts`, because the vocabulary is
        presentation context the caller supplies — a bare `render_md_table`
        call has none in scope, so testing that way would prove nothing about
        what actually ships."""
        answers = g.load_answers(fake_project)
        vars_ = g.collect_vars(fake_project, answers)
        var = next(v for v in vars_ if v.suffix == "OIDC_JWT_SIGNING_KEY")
        assert "JWTs" in var.help  # sanity: core's text has it

        g.write_artifacts(fake_project, check=False)
        for rel in ("docs/guides/authentication.md", "docs/deployment/oidc.md"):
            text = (fake_project / rel).read_text(encoding="utf-8")
            assert var.name in text  # sanity: the var reached this page
            assert "JWTs" not in text, rel
            assert "JSON Web Tokens" in text, rel

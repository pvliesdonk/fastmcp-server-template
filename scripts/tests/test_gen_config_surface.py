def _seed_server_json(project_root: Path) -> None:
    """A minimal `server.json` carrying the keys the splice must leave untouched.

    `kind: json-splice` is a *spliced* artifact like `kind: splice`: the file
    must already exist, since the generator replaces exactly one array per
    package and owns none of the surrounding keys. Both packages are seeded
    with a `STALE` entry so a test can prove the array was genuinely replaced
    rather than merely appended to, and `version`/`identifier` are seeded with
    values `stamp_manifests.py` owns so a test can prove they survive.
    """
    (project_root / "server.json").write_text(
        json.dumps(
            {
                "name": "io.github.demo/demo-mcp",
                "description": "Demo MCP server for template tests.",
                "version": "9.9.9",
                "packages": [
                    {
                        "registryType": "pypi",
                        "identifier": "demo-mcp",
                        "version": "9.9.9",
                        "transport": {"type": "stdio"},
                        "environmentVariables": [
                            {"name": "STALE", "description": "gone"}
                        ],
                    },
                    {
                        "registryType": "oci",
                        "identifier": "ghcr.io/demo/demo-mcp:v9.9.9",
                        "transport": {
                            "type": "streamable-http",
                            "url": "http://localhost:{--port}/mcp",
                        },
                        "environmentVariables": [
                            {"name": "STALE", "description": "gone"}
                        ],
                    },
                ],
            },
            indent=2,
        )
        + "\n",
        encoding="utf-8",
    )


def _seed_mcpb_manifest(project_root: Path) -> None:
    """A minimal mcpb manifest carrying the keys the splice must leave untouched.

    `kind: mcpb-user-config` is a spliced artifact: the file must already
    exist, since the generator replaces exactly the `user_config` and
    `server.mcp_config.env` objects and owns none of the surrounding
    manifest. Both objects are seeded with a STALE entry so a test can prove
    they were genuinely replaced, and `version`/the `--from` pin keep their
    `${VERSION}` placeholders so a test can prove envsubst templating
    survives the round-trip.
    """
    mcpb_dir = project_root / "packaging" / "mcpb"
    mcpb_dir.mkdir(parents=True, exist_ok=True)
    (mcpb_dir / "manifest.json.in").write_text(
        json.dumps(
            {
                "manifest_version": "0.4",
                "name": "demo-mcp",
                "version": "${VERSION}",
                "server": {
                    "type": "uv",
                    "entry_point": "src/server.py",
                    "mcp_config": {
                        "command": "uvx",
                        "args": ["--from", "demo-mcp[all]==${VERSION}", "demo-mcp"],
                        "env": {"STALE": "${user_config.stale}"},
                    },
                },
                "user_config": {
                    "stale": {"type": "string", "title": "Gone", "required": False}
                },
                "compatibility": {"claude_desktop": ">=0.10.0"},
            },
            indent=2,
        )
        + "\n",
        encoding="utf-8",
    )


def _mcpb_manifest(project_root: Path) -> dict:
    return json.loads(
        (project_root / "packaging" / "mcpb" / "manifest.json.in").read_text(
            encoding="utf-8"
        )
    )


def _server_json(project_root: Path) -> dict:
    return json.loads((project_root / "server.json").read_text(encoding="utf-8"))


def _env_names(project_root: Path, package_index: int) -> list[str]:
    pkg = _server_json(project_root)["packages"][package_index]
    return [entry["name"] for entry in pkg["environmentVariables"]]


def _env_entry(project_root: Path, package_index: int, name: str) -> dict:
    pkg = _server_json(project_root)["packages"][package_index]
    return next(e for e in pkg["environmentVariables"] if e["name"] == name)


